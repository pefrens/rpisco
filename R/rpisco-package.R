#' rpisco: Access and Process PISCO High-Resolution Climate Grids for Peru
#'
#' @description
#' The `rpisco` package provides programmatic access, automated caching,
#' spatial subsetting, temporal analysis, and hydrological validation metrics
#' for the Peruvian Interpolated data of SENAMHI's Climatological and
#' hydrological Observations (PISCO).
#'
#' @details
#' Specifically supports PISCOp v3.0 (1981-2025) gridded daily, monthly, and
#' normal climatology rainfall datasets published by Gutierrez and
#' Lavado-Casimiro (2025) on Figshare (<doi:10.6084/m9.figshare.32411886>)
#' and documented in the official technical publication of the Servicio
#' Nacional de Meteorologia e Hidrologia del Peru (SENAMHI):
#' <https://hdl.handle.net/20.500.12542/4183>.
#'
#' @keywords internal
